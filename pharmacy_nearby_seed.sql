-- 4. المخزون — نفس 20 دواء في كل الفروع (بكميات مختلفة)
--
-- السبب: عشان تقدر تتيست "أقرب صيدلية عندها دواء X"
--   → لو كل فرع عنده أدوية مختلفة، ممكن تبحث عن دواء مش موجود في أي فرع قريب
--   → نفس الـ 20 دواء في الـ 30 فرع يضمن إن البحث دايماً يلاقي نتائج
--
-- الاختيار: أول 20 دواء نشط مرتبين أبجدياً (ثابت في كل تشغيل)
-- الكميات: متنوعة — بعض الفروع عندها مخزون عالي وبعضها منخفض أو صفر
-- ==========================================================================

-- جدول مؤقت للـ 20 دواء المشتركة
DROP TABLE IF EXISTS #SharedDrugs;
SELECT TOP 20
    DrugId,
    Price
INTO #SharedDrugs
FROM [Drugs]
WHERE IsActive = 1
ORDER BY BrandName ASC;   -- ترتيب ثابت → نفس الـ 20 دواء في كل تشغيل

-- جدول مؤقت للفروع الجديدة
DROP TABLE IF EXISTS #NewBranches;
CREATE TABLE #NewBranches (BranchId UNIQUEIDENTIFIER);
INSERT INTO #NewBranches VALUES
(@B1),(@B2),(@B3),(@B4),(@B5),(@B6),(@B7),(@B8),(@B9),(@B10),
(@B11),(@B12),(@B13),(@B14),(@B15),(@B16),(@B17),(@B18),(@B19),(@B20),
(@B21),(@B22),(@B23),(@B24),(@B25),(@B26),(@B27),(@B28),(@B29),(@B30);

-- إدراج المخزون: 30 فرع × 20 دواء = 600 سجل
-- الفروع القريبة (B1-B12) → مخزون أعلى عموماً
-- الفروع البعيدة (B25-B30) → مخزون أقل
INSERT INTO [PharmacyInventories]
    ([InventoryId],[BranchId],[DrugId],
     [StockQuantity],[ReservedQuantity],[UnitPrice],
     [ExpiryDate],[LastSyncedAt],[ReorderPoint])
SELECT
    NEWID()       AS [InventoryId],
    b.BranchId,
    d.DrugId,

    -- كمية المخزون: متنوعة لإثراء التيست
    -- (بعض الفروع صفر → يُستبعد من البحث، باقيهم يظهروا مرتبين بالمسافة)
    CASE (ABS(CHECKSUM(NEWID())) % 20)
        WHEN 0  THEN 0     -- نفاد  ← فرع مش هيظهر لهذا الدواء
        WHEN 1  THEN 0
        WHEN 2  THEN 0
        WHEN 3  THEN 0
        WHEN 4  THEN 8     -- منخفض
        WHEN 5  THEN 12
        WHEN 6  THEN 18
        WHEN 7  THEN 25
        WHEN 8  THEN 40    -- متوفر
        WHEN 9  THEN 60
        WHEN 10 THEN 80
        WHEN 11 THEN 100
        WHEN 12 THEN 130
        WHEN 13 THEN 160
        WHEN 14 THEN 200
        WHEN 15 THEN 250
        WHEN 16 THEN 300
        WHEN 17 THEN 350
        WHEN 18 THEN 420
        ELSE        500
    END AS [StockQuantity],

    ABS(CHECKSUM(NEWID())) % 10 AS [ReservedQuantity],

    -- سعر الوحدة = سعر الدواء + هامش صيدلية (5%–35%)
    CAST(
        CASE
            WHEN d.Price > 0
            THEN d.Price * (1.05 + (CAST(ABS(CHECKSUM(NEWID())) % 31 AS DECIMAL(5,2)) / 100.0))
            ELSE 25.00 + (ABS(CHECKSUM(NEWID())) % 175)
        END
    AS DECIMAL(18,2)) AS [UnitPrice],

    -- تاريخ الصلاحية: 3 أشهر → سنتين
    CAST(DATEADD(day,
        90 + (ABS(CHECKSUM(NEWID())) % 641),
        CAST(GETDATE() AS DATE)
    ) AS DATE) AS [ExpiryDate],

    GETUTCDATE() AS [LastSyncedAt],

    10 + (ABS(CHECKSUM(NEWID())) % 16) AS [ReorderPoint]

FROM #NewBranches b
CROSS JOIN #SharedDrugs d;   -- نفس الـ 20 دواء لكل الفروع

DROP TABLE IF EXISTS #SharedDrugs;
DROP TABLE IF EXISTS #NewBranches;


